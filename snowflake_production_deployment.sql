USE SCHEMA F1_DATA_WAREHOUSE.CORE;

-- DIM_SEASON: Tracks technical regulation eras and aerodynamic changes
CREATE OR REPLACE TABLE DIM_SEASON (
    SEASON_YEAR NUMBER(4,0) PRIMARY KEY,
    TECHNICAL_REGULATIONS_ERA VARCHAR(100) NOT NULL,
    ENGINE_ARCHITECTURE VARCHAR(100) NOT NULL,
    MIN_WEIGHT_KG NUMBER(5,1) NOT NULL,
    BASE_HORSEPOWER NUMBER(6,1) NOT NULL,
    TOTAL_ROUNDS_SCHEDULED NUMBER(3,0) NOT NULL
);

-- DIM_CIRCUIT: Circuit geometry, altitude, and official FIA track lap records
CREATE OR REPLACE TABLE DIM_CIRCUIT (
    CIRCUIT_ID NUMBER(38,0) PRIMARY KEY,
    CIRCUIT_REF VARCHAR(50) NOT NULL UNIQUE,
    CIRCUIT_NAME VARCHAR(150) NOT NULL,
    CIRCUIT_LOCATION VARCHAR(100),
    CIRCUIT_COUNTRY VARCHAR(100) NOT NULL,
    CIRCUIT_LATITUDE FLOAT,
    CIRCUIT_LONGITUDE FLOAT,
    CIRCUIT_ALTITUDE_M NUMBER(6,0),
    LENGTH_KM FLOAT NOT NULL,
    TURNS_COUNT NUMBER(3,0),
    -- Track Lap Record Reference Pillar
    OFFICIAL_LAP_RECORD_SEC FLOAT NOT NULL,
    OFFICIAL_LAP_RECORD_STR VARCHAR(20) NOT NULL,
    RECORD_HOLDER_DRIVER_NAME VARCHAR(100) NOT NULL,
    RECORD_ESTABLISHED_YEAR NUMBER(4,0) NOT NULL,
    PIT_LANE_TIME_LOSS_SEC FLOAT NOT NULL
);

-- DIM_CONSTRUCTOR: Team engineering specs, power unit suppliers, and DHL pit ratings
CREATE OR REPLACE TABLE DIM_CONSTRUCTOR (
    CONSTRUCTOR_ID NUMBER(38,0) PRIMARY KEY,
    CONSTRUCTOR_REF VARCHAR(50) NOT NULL UNIQUE,
    CONSTRUCTOR_NAME VARCHAR(100) NOT NULL,
    CONSTRUCTOR_NATIONALITY VARCHAR(50) NOT NULL,
    DEFAULT_POWER_UNIT_SUPPLIER VARCHAR(100) NOT NULL,
    BASE_RELIABILITY_SCORE FLOAT NOT NULL,
    DHL_PIT_CREW_EFFICIENCY_RATING FLOAT NOT NULL,
    COLOR_HEX VARCHAR(10) NOT NULL
);

-- DIM_DRIVER: Driver identification, permanent number, nationality
CREATE OR REPLACE TABLE DIM_DRIVER (
    DRIVER_ID NUMBER(38,0) PRIMARY KEY,
    DRIVER_REF VARCHAR(50) NOT NULL UNIQUE,
    DRIVER_CODE VARCHAR(3) NOT NULL,
    DRIVER_NUMBER NUMBER(3,0),
    DRIVER_NAME VARCHAR(100) NOT NULL,
    DRIVER_NATIONALITY VARCHAR(50) NOT NULL,
    DRIVER_DOB DATE,
    CAREER_TOTAL_ENTRIES NUMBER(5,0),
    CAREER_TOTAL_WINS NUMBER(5,0)
);

-- DIM_RACE: Individual Grand Prix calendar schedule
CREATE OR REPLACE TABLE DIM_RACE (
    RACE_ID NUMBER(38,0) PRIMARY KEY,
    SEASON_YEAR NUMBER(4,0) NOT NULL REFERENCES DIM_SEASON(SEASON_YEAR),
    ROUND_NUMBER NUMBER(3,0) NOT NULL,
    RACE_NAME VARCHAR(100) NOT NULL,
    CIRCUIT_ID NUMBER(38,0) NOT NULL REFERENCES DIM_CIRCUIT(CIRCUIT_ID),
    RACE_DATE DATE NOT NULL,
    TOTAL_RACE_LAPS NUMBER(4,0) NOT NULL
);

