-- ----------------------------------------------------------------------------
-- 7. SNOWFLAKE OPTIMIZED ANALYTICAL QUERIES (OLAP & WINNER PREDICTION)
-- ----------------------------------------------------------------------------

-- QUERY 1: CAR FEATURES COMPARISON ACROSS ENGINE REGULATION ERAS (SNOWFLAKE PIVOT)
-- Evaluates BHP, Weight, and Power-to-Weight across Turbo Hybrid vs Ground Effect
SELECT 
    SEASON_YEAR,
    CONSTRUCTOR_NAME,
    AVG(CAR_ESTIMATED_POWER_BHP) AS AVG_BHP,
    AVG(CAR_POWER_TO_WEIGHT_RATIO) AS AVG_POWER_TO_WEIGHT,
    AVG(CAR_MECHANICAL_RELIABILITY_SCORE) AS AVG_RELIABILITY_SCORE,
    COUNT(CASE WHEN IS_MECHANICAL_DNF = 1 THEN 1 END) AS TOTAL_ENGINE_FAILURES,
    SUM(IS_WIN) AS TOTAL_ERA_WINS
FROM F1_DATA_WAREHOUSE.ML_MARTS.F1_WINNER_PREDICTION_FEATURE_STORE
WHERE SEASON_YEAR >= 2014
GROUP BY SEASON_YEAR, CONSTRUCTOR_NAME
ORDER BY SEASON_YEAR DESC, TOTAL_ERA_WINS DESC;

-- QUERY 2: LAP RECORD PACE BENCHMARK WITH SNOWFLAKE QUALIFY CLAUSE
-- Finds drivers within 1.0 second of circuit track lap record across all 2024 Grands Prix
SELECT 
    RACE_ID,
    ROUND_NUMBER,
    DRIVER_CODE,
    CONSTRUCTOR_NAME,
    FASTEST_LAP_SPEED,
    CIRCUIT_LAP_RECORD_SEC,
    DRIVER_LAP_RECORD_DELTA_SEC,
    DRIVER_LAP_RECORD_RATIO,
    IS_WIN,
    RANK() OVER (PARTITION BY RACE_ID ORDER BY DRIVER_LAP_RECORD_DELTA_SEC ASC) AS PACE_RANK
FROM F1_DATA_WAREHOUSE.ML_MARTS.F1_WINNER_PREDICTION_FEATURE_STORE
WHERE SEASON_YEAR = 2024
QUALIFY PACE_RANK <= 5
ORDER BY RACE_ID, PACE_RANK;

-- QUERY 3: PIT STOP TIME EFFICIENCY & STRATEGY CONVERSION (WINDOW STATS)
-- Quantifies how stationary pit gun duration and pit crew rating impact podium conversions
SELECT 
    CONSTRUCTOR_NAME,
    COUNT(*) AS TOTAL_RACE_STINTS,
    AVG(PIT_STOP_COUNT) AS AVG_STOPS_PER_GP,
    AVG(TOTAL_RACE_PIT_LOSS_SEC) AS AVG_TOTAL_PIT_LOSS_SEC,
    AVG(ESTIMATED_STATIONARY_PIT_SEC) AS AVG_WHEEL_GUN_STATIONARY_SEC,
    AVG(PIT_CREW_EFFICIENCY_SCORE) AS AVG_DHL_CREW_SCORE,
    SUM(IS_WIN) AS WINS_ACHIEVED,
    ROUND(SUM(IS_WIN) * 100.0 / COUNT(*), 2) AS WIN_CONVERSION_PCT,
    ROUND(SUM(IS_PODIUM) * 100.0 / COUNT(*), 2) AS PODIUM_CONVERSION_PCT
FROM F1_DATA_WAREHOUSE.ML_MARTS.F1_WINNER_PREDICTION_FEATURE_STORE
WHERE SEASON_YEAR >= 2022
GROUP BY CONSTRUCTOR_NAME
HAVING COUNT(*) >= 20
ORDER BY WIN_CONVERSION_PCT DESC, AVG_DHL_CREW_SCORE DESC;

-- QUERY 4: SNOWFLAKE MATCH_RECOGNIZE PATTERN MINING FOR UNDERCUT STRATEGIES
-- Identifies sequence patterns where a pit stop leads to track position overtakes
SELECT *
FROM F1_DATA_WAREHOUSE.CORE.FACT_LAP_TIMES
MATCH_RECOGNIZE (
    PARTITION BY RACE_ID, DRIVER_ID
    ORDER BY LAP_NUMBER
    MEASURES
        FIRST(LAP_POSITION) AS PRE_PIT_POS,
        LAST(LAP_POSITION) AS POST_OUTLAP_POS,
        FIRST(LAP_NUMBER) AS INLAP_NUM,
        LAST(LAP_NUMBER) AS OUTLAP_NUM
    ONE ROW PER MATCH
    AFTER MATCH SKIP PAST LAST ROW
    PATTERN (PIT_LAP OUT_LAP SPRINT_LAP+)
    DEFINE
        PIT_LAP AS IS_PIT_LAP = 1,
        OUT_LAP AS IS_PIT_LAP = 0 AND LAP_POSITION <= PRE_PIT_POS + 3,
        SPRINT_LAP AS LAP_POSITION < PRE_PIT_POS
)
ORDER BY RACE_ID, INLAP_NUM;

-- QUERY 5: MODEL FEATURE VECTOR EXTRACTION FOR REAL-TIME SCORING (SNOWFLAKE ARRAY_AGG)
-- Prepares JSON-ready 24-feature vector for ingestion into Snowpark / Python inference
SELECT 
    RACE_ID,
    DRIVER_CODE,
    CONSTRUCTOR_NAME,
    OBJECT_CONSTRUCT(
        'car_features', OBJECT_CONSTRUCT(
            'bhp', CAR_ESTIMATED_POWER_BHP,
            'p2w', CAR_POWER_TO_WEIGHT_RATIO,
            'weight', CAR_MIN_WEIGHT_KG,
            'rel_score', CAR_MECHANICAL_RELIABILITY_SCORE,
            'pace_idx', CONSTRUCTOR_PACE_INDEX
        ),
        'lap_records', OBJECT_CONSTRUCT(
            'track_rec_sec', CIRCUIT_LAP_RECORD_SEC,
            'delta_sec', DRIVER_LAP_RECORD_DELTA_SEC,
            'pace_ratio', DRIVER_LAP_RECORD_RATIO,
            'quali_delta', DRIVER_QUALI_TO_RECORD_DELTA_SEC
        ),
        'pit_stops', OBJECT_CONSTRUCT(
            'stops', PIT_STOP_COUNT,
            'total_loss', TOTAL_RACE_PIT_LOSS_SEC,
            'crew_score', PIT_CREW_EFFICIENCY_SCORE,
            'stationary', ESTIMATED_STATIONARY_PIT_SEC
        ),
        'context', OBJECT_CONSTRUCT(
            'grid', GRID_POSITION,
            'points', DRIVER_STANDING_POINTS,
            'wins', DRIVER_CHAMPIONSHIP_WINS
        )
    ) AS ML_FEATURE_VECTOR_JSON
FROM F1_DATA_WAREHOUSE.ML_MARTS.F1_WINNER_PREDICTION_FEATURE_STORE
WHERE RACE_ID = 1129 -- 2024 British GP
ORDER BY GRID_POSITION ASC;
